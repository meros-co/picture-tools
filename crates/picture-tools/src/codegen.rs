fn uniform_vectors_json() -> String {
    let vectors: Vec<serde_json::Value> = sample_params()
        .into_iter()
        .map(|(name, p, lut_size, time)| {
            let floats: Vec<f32> = uniforms_for(&p, [320.0, 180.0], lut_size, time).into_iter().flat_map(|u| u.value).collect();
            serde_json::json!({ "name": name, "params": p, "size": [320.0, 180.0], "lut_size": lut_size, "time": time, "floats": floats })
        })
        .collect();
    let mut s = serde_json::to_string_pretty(&serde_json::json!({ "vectors": vectors })).unwrap();
    s.push('\n');
    s
}

/// A small test picture: ramp, bars, a ramp into clipping, an edge.
fn case_picture(w: u32, h: u32) -> Vec<u8> {
    let bars: [[u8; 3]; 8] = [[191, 191, 191], [191, 191, 0], [0, 191, 191], [0, 191, 0], [191, 0, 191], [191, 0, 0], [0, 0, 191], [0, 0, 0]];
    let mut px = Vec::with_capacity((w * h * 4) as usize);
    for y in 0..h {
        for x in 0..w {
            let c = match y * 4 / h {
                0 => [(x * 255 / (w - 1)) as u8; 3],
                1 => bars[(x * 8 / w) as usize],
                2 => [(230 + x * 25 / (w - 1)) as u8; 3],
                _ => if x < w / 2 { [10, 10, 10] } else { [240, 240, 240] },
            };
            px.extend([c[0], c[1], c[2], 255]);
        }
    }
    px
}

fn shader_cases_json() -> String {
    let (w, h) = (48u32, 32u32);
    let image = case_picture(w, h);
    // On 8-bit steps, as the atlas holds them.
    let mut lut = Lut3d::per_channel(17, |x| x.powf(0.8));
    for v in &mut lut.data {
        *v = v.map(|c| (c * 255.0).round() / 255.0);
    }
    let cases: Vec<serde_json::Value> = sample_params()
        .into_iter()
        .map(|(name, p, _, time)| {
            let l = p.lut.then_some(&lut);
            let mut expected = image.clone();
            apply_cpu(&p, l, &mut expected, w, h, time);
            let floats: Vec<f32> = uniforms_for(&p, [w as f32, h as f32], l.map_or(33, |l| l.size), time).into_iter().flat_map(|u| u.value).collect();
            let atlas = l.map(|l| {
                let (aw, ah, px) = l.atlas_rgba8();
                serde_json::json!({ "w": aw, "h": ah, "px": b64(&px) })
            });
            serde_json::json!({ "name": name, "floats": floats, "lut": atlas, "expected": b64(&expected) })
        })
        .collect();
    let mut s = serde_json::to_string(&serde_json::json!({ "w": w, "h": h, "image": b64(&image), "cases": cases })).unwrap();
    s.push('\n');
    s
}

fn kind_of(name: &str) -> Option<UniformKind> {
    UNIFORMS.iter().find(|d| d.name == name).map(|d| d.kind)
}

/// The template's body (comments at the top dropped) in `d`.
fn body(d: Dialect) -> String {
    let template = TEMPLATE.replace("\r\n", "\n");
    let start = template.find("vec3 mpt_lut(").expect("template body");
    // From the comment above the first function.
    let from = template[..start].rfind("\n\n").map_or(start, |c| c + 2);
    let mut s = template[from..].to_string();
    let (sample_input, sample_lut) = match d {
        Dialect::Flutter | Dialect::Gles3 => ("texture(u_input, ", "texture(u_lut_tex, "),
        Dialect::Webgl1 => ("texture2D(u_input, ", "texture2D(u_lut_tex, "),
        Dialect::Metal => ("u_input.sample(smp, ", "u_lut_tex.sample(smp, "),
    };
    s = s.replace("SAMPLE_INPUT(", sample_input).replace("SAMPLE_LUT(", sample_lut);
    match d {
        Dialect::Metal => {
            s = s
                .replace(" MPT_ARGS)", ", constant MptUniforms& u, texture2d<float> u_input, texture2d<float> u_lut_tex, sampler smp)")
                .replace(" MPT_PASS)", ", u, u_input, u_lut_tex, smp)");
            s = metal_uniforms(&s);
            s = s.replace("vec2", "float2").replace("vec3", "float3").replace("vec4", "float4");
        }
        _ => {
            s = s.replace(" MPT_ARGS)", ")").replace(" MPT_PASS)", ")").replace("mpt_mod(", "mod(");
            s = replace_uniform_prefix(&s, |name, index| format!("{name}{index}"));
        }
    }
    s
}

/// `U.name` → `u.name`, wrapping vector uniforms as plain vectors (the
/// struct packs them).
fn metal_uniforms(s: &str) -> String {
    replace_uniform_prefix(s, |name, index| {
        let access = format!("u.{name}{index}");
        match kind_of(name) {
            Some(UniformKind::Vec2) => format!("float2({access})"),
            Some(UniformKind::Vec3) => format!("float3({access})"),
            _ => access,
        }
    })
}

/// Rewrites each `U.name` or `U.name[i]` (with `U` not part of a longer
/// word) as `f(name, "[i]")`.
fn replace_uniform_prefix(s: &str, f: impl Fn(&str, &str) -> String) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(i) = rest.find("U.") {
        let starts_word = rest[..i].chars().last().is_none_or(|c| !(c.is_ascii_alphanumeric() || c == '_'));
        if !starts_word {
            out.push_str(&rest[..i + 2]);
            rest = &rest[i + 2..];
            continue;
        }
        out.push_str(&rest[..i]);
        let after = &rest[i + 2..];
        let name_len = after.find(|c: char| !(c.is_ascii_alphanumeric() || c == '_')).unwrap_or(after.len());
        let name = &after[..name_len];
        let mut tail = &after[name_len..];
        let mut index = String::new();
        if tail.starts_with('[') {
            let close = tail.find(']').unwrap();
            index = tail[..=close].to_string();
            tail = &tail[close + 1..];
        }
        out.push_str(&f(name, &index));
        rest = tail;
    }
    out.push_str(rest);
    out
}

/// GLSL uniform declarations from the table.
fn glsl_uniforms(external_input: bool) -> String {
    let mut s = String::new();
    for u in UNIFORMS {
        let array = if u.count > 1 { format!("[{}]", u.count) } else { String::new() };
        let note = if u.unit.is_empty() { u.doc.to_string() } else { format!("{} ({})", u.doc, u.unit) };
        if external_input && u.name == "u_input" {
            s.push_str("#ifdef MPT_EXTERNAL_INPUT\nuniform samplerExternalOES u_input;\n#else\nuniform sampler2D u_input;\n#endif\n");
            continue;
        }
        s.push_str(&format!("uniform {} {}{}; // {}\n", u.kind.glsl(), u.name, array, note));
    }
    s
}

/// The Metal uniform struct: packed, so it's the plain floats of
/// `mpt_uniforms` in order.
fn metal_struct() -> String {
    let mut s = String::from("// The plain uniforms, packed: exactly the floats `mpt_uniforms` writes, in\n// order (see shaders/uniforms.json).\nstruct MptUniforms {\n");
    for u in UNIFORMS.iter().filter(|u| u.kind != UniformKind::Sampler2D) {
        let ty = match u.kind {
            UniformKind::Float => "float",
            UniformKind::Vec2 => "packed_float2",
            UniformKind::Vec3 => "packed_float3",
            UniformKind::Sampler2D => unreachable!(),
        };
        let array = if u.count > 1 { format!("[{}]", u.count) } else { String::new() };
        s.push_str(&format!("  {ty} {}{array};\n", u.name));
    }
    s.push_str("};\n");
    s
}

/// One dialect's shader.
pub fn generate(d: Dialect) -> String {
    let body = body(d);
    match d {
        Dialect::Flutter => format!(
            "{NOTICE}// Flutter runtime effect: an ImageFilter.shader or FragmentProgram. The\n// engine sets u_size and u_input for an image filter; the rest follow\n// (setFloat from index 2).\n#include <flutter/runtime_effect.glsl>\n\n{}\nout vec4 frag_color;\n\nvec2 mpt_uv(vec2 frag) {{\n  vec2 uv = frag / u_size;\n#ifdef IMPELLER_TARGET_OPENGLES\n  uv.y = 1.0 - uv.y;\n#endif\n  return uv;\n}}\n\n{body}\nvoid main() {{\n  frag_color = mpt_shade(FlutterFragCoord().xy);\n}}\n",
            glsl_uniforms(false)
        ),
        Dialect::Webgl1 => format!(
            "{NOTICE}// WebGL 1 (GLSL ES 1.00). The picture is uploaded top row first (no\n// UNPACK_FLIP_Y); draw a quad over the viewport, which is u_size.\n#ifdef GL_FRAGMENT_PRECISION_HIGH\nprecision highp float;\n#else\nprecision mediump float;\n#endif\n\n{}\nvec2 mpt_uv(vec2 frag) {{\n  return frag / u_size;\n}}\n\n{body}\nvoid main() {{\n  gl_FragColor = mpt_shade(vec2(gl_FragCoord.x, u_size.y - gl_FragCoord.y));\n}}\n",
            glsl_uniforms(false)
        ),
        Dialect::Gles3 => format!(
            "#version 300 es\n{NOTICE}// OpenGL ES 3.0. The vertex stage passes the picture's texture coordinate\n// as v_uv. For a camera's external texture, add\n// `#define MPT_EXTERNAL_INPUT` on the line after #version.\n#ifdef MPT_EXTERNAL_INPUT\n#extension GL_OES_EGL_image_external_essl3 : require\n#endif\nprecision highp float;\n\n{}\nin vec2 v_uv;\nout vec4 frag_color;\n\n// This pixel, so neighbors can be sampled relative to v_uv.\nvec2 mpt_frag0;\n\nvec2 mpt_uv(vec2 frag) {{\n  return v_uv + (frag - mpt_frag0) / u_size;\n}}\n\n{body}\nvoid main() {{\n  mpt_frag0 = vec2(gl_FragCoord.x, u_size.y - gl_FragCoord.y);\n  frag_color = mpt_shade(mpt_frag0);\n}}\n",
            glsl_uniforms(true)
        ),
        Dialect::Metal => format!(
            "{NOTICE}// Metal: picture_tools_vertex draws a full-screen triangle and\n// picture_tools_fragment the tools. Uniforms at buffer 0, the picture at\n// texture 0, the LUT atlas at texture 1 (bind any texture there when the\n// LUT is off: it isn't sampled).\n#include <metal_stdlib>\nusing namespace metal;\n\n{}\nstruct MptVertexOut {{\n  float4 position [[position]];\n}};\n\nvertex MptVertexOut picture_tools_vertex(uint vid [[vertex_id]]) {{\n  float2 p = float2(float((vid << 1) & 2), float(vid & 2));\n  MptVertexOut out;\n  out.position = float4(p * 2.0 - 1.0, 0.0, 1.0);\n  return out;\n}}\n\ninline float mpt_mod(float x, float y) {{\n  return x - y * floor(x / y);\n}}\n\nfloat2 mpt_uv(float2 frag, constant MptUniforms& u, texture2d<float> u_input, texture2d<float> u_lut_tex, sampler smp) {{\n  return frag / float2(u.u_size);\n}}\n\n{}\nfragment float4 picture_tools_fragment(\n    MptVertexOut in [[stage_in]],\n    constant MptUniforms& u [[buffer(0)]],\n    texture2d<float> u_input [[texture(0)]],\n    texture2d<float> u_lut_tex [[texture(1)]]) {{\n  constexpr sampler smp(address::clamp_to_edge, filter::linear);\n  return mpt_shade(in.position.xy, u, u_input, u_lut_tex, smp);\n}}\n",
            metal_struct(),
            body
        ),
    }
}

/// `shaders/uniforms.json`: each uniform's name, type, array length, unit,
/// meaning and float offset in `mpt_uniforms`' output.
pub fn uniforms_json() -> String {
    let mut offset = 0usize;
    let mut entries = Vec::new();
    for u in UNIFORMS {
        let floats = u.kind.floats() * u.count;
        let off = if u.kind == UniformKind::Sampler2D { serde_json::Value::Null } else { offset.into() };
        entries.push(serde_json::json!({
            "name": u.name,
            "type": u.kind.glsl(),
            "count": u.count,
            "unit": u.unit,
            "doc": u.doc,
            "offset": off,
        }));
        offset += floats;
    }
    let doc = serde_json::json!({
        "comment": "Generated by picture-tools-gen from crates/picture-tools/src/tools.rs. The shader uniforms in declaration order; `offset` is the index of a uniform's first float in mpt_uniforms' output (samplers have none).",
        "floats": offset,
        "uniforms": entries,
    });
    let mut s = serde_json::to_string_pretty(&doc).unwrap();
    s.push('\n');
    s
}
