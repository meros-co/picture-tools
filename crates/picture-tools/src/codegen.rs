//! Generates the shader dialects and `uniforms.json` from
//! `shaders/picture_tools.glsl.in` and [`crate::tools::UNIFORMS`]. The
//! `picture-tools-gen` tool writes the results into the repo; a test fails
//! if what's committed differs from what this makes.

use crate::tools::{UNIFORMS, UniformKind};

/// The template (see its header for the subset it's written in).
pub const TEMPLATE: &str = include_str!("../../../shaders/picture_tools.glsl.in");

const NOTICE: &str = "// Generated by picture-tools-gen from shaders/picture_tools.glsl.in and the\n// uniform table in crates/picture-tools/src/tools.rs. Don't edit; regenerate.\n";

/// The shader dialects.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Dialect {
    /// Flutter runtime effects (`FragmentProgram`, `ImageFilter.shader`).
    Flutter,
    /// OpenGL ES 3.0 (`#version 300 es`).
    Gles3,
    /// Metal.
    Metal,
    /// WebGL 1 (GLSL ES 1.00).
    Webgl1,
}

/// Every generated file: (path from the repo root, contents), with LF
/// line ends whatever the checkout's.
pub fn files() -> Vec<(&'static str, String)> {
    files_raw().into_iter().map(|(p, s)| (p, s.replace("\r\n", "\n"))).collect()
}

fn files_raw() -> Vec<(&'static str, String)> {
    let flutter = generate(Dialect::Flutter);
    let metal = generate(Dialect::Metal);
    vec![
        ("shaders/gen/flutter/picture_tools.frag", flutter.clone()),
        ("shaders/gen/gles3/picture_tools.frag", generate(Dialect::Gles3)),
        ("shaders/gen/metal/picture_tools.metal", metal.clone()),
        ("shaders/gen/webgl1/picture_tools.frag", generate(Dialect::Webgl1)),
        ("shaders/uniforms.json", uniforms_json()),
        // The packages carry their own copies, as their tools need them
        // inside the package.
        ("flutter/shaders/picture_tools.frag", flutter),
        ("swift/Sources/MerosPictureTools/Resources/picture_tools.metal", metal),
        // Test vectors for the Flutter package: its uniform packing and its
        // shader against the CPU reference.
        ("flutter/test/fixtures/uniform_vectors.json", uniform_vectors_json()),
        ("flutter/test/fixtures/shader_cases.json", shader_cases_json()),
    ]
}

fn b64(data: &[u8]) -> String {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b = [chunk[0], *chunk.get(1).unwrap_or(&0), *chunk.get(2).unwrap_or(&0)];
        let n = (b[0] as u32) << 16 | (b[1] as u32) << 8 | b[2] as u32;
        for i in 0..4 {
            out.push(if i <= chunk.len() { T[(n >> (18 - 6 * i) & 63) as usize] as char } else { '=' });
        }
    }
    out
}

